/** Russian name for a code, or the code itself if it is not one we know. */
export function countryName(code: string | null | undefined): string {
  if (!code) return "";
  const upper = code.toUpperCase();
  return COUNTRIES.find(([c]) => c === upper)?.[1] ?? upper;
}

export function isKnownCountry(code: string | null | undefined): boolean {
  if (!code) return false;
  const upper = code.toUpperCase();
  return COUNTRIES.some(([c]) => c === upper);
}
