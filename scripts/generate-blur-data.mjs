import { readdir, stat, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";
import sharp from "sharp";

const ROOT = dirname(fileURLToPath(import.meta.url));
const PUBLIC_DIR = join(ROOT, "..", "public");
const OUT_FILE = join(ROOT, "..", "src", "lib", "blur-data.ts");

const EXTS = new Set([".png", ".jpg", ".jpeg", ".webp"]);
const IGNORE_DIRS = new Set(["tmp_b64"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) {
      if (IGNORE_DIRS.has(e.name)) continue;
      files.push(...(await walk(full)));
    } else if (EXTS.has(extname(e.name))) {
      files.push(full);
    }
  }
  return files;
}

function extname(name) {
  const i = name.lastIndexOf(".");
  return i < 0 ? "" : name.slice(i).toLowerCase();
}

async function toBlurDataURL(absPath) {
  const buf = await sharp(absPath)
    .resize(12, 12, { fit: "inside" })
    .jpeg({ quality: 40 })
    .toBuffer();
  return `data:image/jpeg;base64,${buf.toString("base64")}`;
}

async function main() {
  const files = await walk(PUBLIC_DIR);
  const entries = [];
  for (const abs of files.sort()) {
    const rel = "/" + relative(PUBLIC_DIR, abs).split(sep).join("/");
    try {
      const dataUrl = await toBlurDataURL(abs);
      entries.push([rel, dataUrl]);
      console.log(`  ${rel}  (${dataUrl.length}b)`);
    } catch (err) {
      console.warn(`  skip ${rel}: ${err.message}`);
    }
  }

  const body = `// Auto-generated by scripts/generate-blur-data.mjs — do not edit by hand.
// Run \`npm run blur-data\` after adding or replacing images in public/.

export const BLUR_DATA: Record<string, string> = {
${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};

export function getBlurProps(src: string): { placeholder?: "blur"; blurDataURL?: string } {
  const url = BLUR_DATA[src];
  return url ? { placeholder: "blur", blurDataURL: url } : {};
}
`;

  await writeFile(OUT_FILE, body, "utf8");
  console.log(`\nWrote ${entries.length} entries to ${relative(ROOT, OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
